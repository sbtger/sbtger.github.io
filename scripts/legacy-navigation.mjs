import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const archiveRoot = fileURLToPath(new URL('../archives/', import.meta.url));
const generated = '<!-- Generated by writeArchivePeriods -->';

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
}

function formatPeriod(key) {
  const [year, month] = key.split('/');
  return month ? `${year}年${Number(month)}月` : `${year}年`;
}

function archivePage(key, posts, months) {
  const label = formatPeriod(key);
  const rows = posts.map(({ slug, title, day }) => {
    const [year, month, date] = day.split('-');
    return `<a href="/articles/${encodeURIComponent(slug)}.html"><span>${escapeHtml(title)}</span><time datetime="${day}">${year}年${Number(month)}月${Number(date)}日</time></a>`;
  });
  const year = key.split('/')[0];
  const periods = months.length ? months : [year];
  const links = periods.map(p => `<a href="/archives/${p}/">${formatPeriod(p)}</a>`).join(' ');
  return `<!doctype html>
${generated}
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${label}文章 · Anred Lab</title>
  <link rel="canonical" href="https://anred.space/archives/${key}/">
  <link rel="stylesheet" href="/assets/site.css">
</head>
<body>
  <main class="shell">
    <article class="frame reader">
      <a class="back" href="/#archive">返回全部文章</a>
      <h1 class="page-title">${label}文章</h1>
      <nav class="page-links" aria-label="按日期浏览">${links}</nav>
      <div class="post-list">
        ${rows.join('\n        ')}
      </div>
    </article>
  </main>
</body>
</html>
`;
}

// Keep date URLs usable even after the last post in a period moves or is removed.
async function redirectEmptyPeriod(key, periods) {
  if (periods.has(key)) return;
  const page = path.join(archiveRoot, key, 'index.html');
  const old = await readFile(page, 'utf8').catch(error => {
    if (error.code === 'ENOENT') return '';
    throw error;
  });
  if (!old.includes(generated) || old.includes('/assets/legacy-redirect.js')) return;
  await writeFile(page, `<!doctype html>
${generated}
<html lang="zh-CN"><head><meta charset="utf-8"><title>全部文章 · Anred Lab</title>
<link rel="canonical" href="https://anred.space/#archive">
<script src="/assets/legacy-redirect.js" defer></script>
<noscript><meta http-equiv="refresh" content="0;url=/#archive"></noscript>
</head><body><p><a href="/#archive">浏览全部文章</a></p></body></html>
`);
}

export async function writeArchivePeriods(posts) {
  const periods = new Map();
  for (const post of posts) {
    const raw = post.date instanceof Date ? post.date.toISOString() : post.date;
    const day = String(raw).slice(0, 10);
    if (!/^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])$/.test(day)) {
      throw new Error(`Invalid archive date for ${post.slug}: ${raw}`);
    }
    const [year, month] = day.split('-');
    for (const key of [year, `${year}/${month}`]) {
      if (!periods.has(key)) periods.set(key, []);
      periods.get(key).push({ ...post, day });
    }
  }
  await mkdir(archiveRoot, { recursive: true });
  for (const [key, entries] of periods) {
    entries.sort((a, b) => b.day.localeCompare(a.day));
    const months = [...periods.keys()].filter(k => k.startsWith(key + '/')).sort().reverse();
    const dir = path.join(archiveRoot, key);
    await mkdir(dir, { recursive: true });
    await writeFile(path.join(dir, 'index.html'), archivePage(key, entries, months));
  }
  for (const year of await readdir(archiveRoot, { withFileTypes: true })) {
    if (!year.isDirectory() || !/^\d{4}$/.test(year.name)) continue;
    await redirectEmptyPeriod(year.name, periods);
    for (const month of await readdir(path.join(archiveRoot, year.name), { withFileTypes: true })) {
      if (month.isDirectory() && /^(0[1-9]|1[0-2])$/.test(month.name)) {
        await redirectEmptyPeriod(year.name + '/' + month.name, periods);
      }
    }
  }
}
